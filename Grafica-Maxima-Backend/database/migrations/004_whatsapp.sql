CREATE TABLE whatsapp_destinatario (
  id_destinatario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  telefone varchar(16) NOT NULL UNIQUE CHECK (telefone ~ '^[+][1-9][0-9]{7,14}$'),
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX whatsapp_destinatario_ativo ON whatsapp_destinatario (ativo, nome);

CREATE TABLE relatorio_envio (
  id_envio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_relatorio integer NOT NULL REFERENCES relatorio(id_relatorio) ON DELETE CASCADE,
  destinatario varchar(16) NOT NULL,
  status varchar(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
  modo varchar(10) NOT NULL CHECK (modo IN ('cloud', 'mock')),
  tentativas smallint NOT NULL DEFAULT 0,
  id_mensagem varchar(255),
  erro text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  enviado_em timestamptz
);

CREATE INDEX relatorio_envio_historico ON relatorio_envio (id_relatorio, criado_em DESC);
