CREATE TABLE relatorio (
  id_relatorio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo varchar(10) NOT NULL CHECK (tipo IN ('weekly', 'monthly')),
  data_inicio date NOT NULL,
  data_fim date NOT NULL,
  dados jsonb NOT NULL,
  resumo text NOT NULL,
  gerado_por integer REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  gerado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tipo, data_inicio, data_fim)
);

CREATE INDEX relatorio_historico ON relatorio (tipo, data_inicio DESC);
