CREATE TABLE usuario (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  email varchar(100),
  login varchar(80) NOT NULL UNIQUE,
  senha_hash varchar(255) NOT NULL,
  tipo varchar(30) NOT NULL CHECK (tipo IN ('admin', 'atendente')),
  data_criacao timestamptz NOT NULL DEFAULT now(),
  ativo boolean NOT NULL DEFAULT true
);

CREATE TABLE cliente (
  id_cliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL,
  cpf_cnpj varchar(20),
  telefone varchar(20),
  email varchar(100),
  endereco text,
  data_cadastro timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX cliente_email ON cliente (lower(email));
CREATE INDEX cliente_documento ON cliente (regexp_replace(coalesce(cpf_cnpj, ''), '[^0-9]', '', 'g'));

CREATE TABLE papel (
  id_papel integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100),
  tipo varchar(50),
  largura_folha numeric(10,2),
  altura_folha numeric(10,2),
  custo_por_folha numeric(18,4)
);

CREATE TABLE impressao (
  id_impressao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo varchar(50),
  custo_por_folha numeric(18,4)
);

CREATE TABLE acabamento (
  id_acabamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(50),
  tipo varchar(30),
  descricao text,
  custo numeric(18,4),
  tipo_cobranca varchar(20),
  custo_fixo numeric(18,4) DEFAULT 0,
  lucro_fixo numeric(18,4) DEFAULT 0,
  lucro_unitario numeric(18,4) DEFAULT 0
);

CREATE TABLE corte (
  id_corte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo varchar(50),
  descricao text,
  valor_fixo numeric(18,4),
  custo_unitario numeric(18,4) DEFAULT 0,
  lucro_fixo numeric(18,4) DEFAULT 0,
  lucro_unitario numeric(18,4) DEFAULT 0
);

CREATE TABLE servico (
  id_servico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100),
  descricao text,
  tipo varchar(30),
  tipo_cobranca varchar(20),
  custo_fixo numeric(18,4),
  custo_unitario numeric(18,4)
);

CREATE TABLE orcamento (
  id_orcamento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer REFERENCES usuario(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  id_cliente integer REFERENCES cliente(id_cliente) ON DELETE SET NULL ON UPDATE CASCADE,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  data_finalizacao timestamptz,
  data_validade timestamptz,
  valor_total numeric(18,4) DEFAULT 0,
  valor_unitario numeric(18,4) DEFAULT 0,
  subtotal numeric(18,4),
  desconto_tipo varchar(12) NOT NULL DEFAULT 'percentual',
  desconto_valor numeric(18,4) NOT NULL DEFAULT 0,
  status varchar(30) NOT NULL DEFAULT 'Em negociação',
  prazo_entrega date,
  observacoes text,
  quantidade integer NOT NULL DEFAULT 1,
  versao integer NOT NULL DEFAULT 1
);

CREATE TABLE material (
  id_material integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria varchar(50) NOT NULL,
  nome varchar(100) NOT NULL,
  custo_fixo numeric(18,4) NOT NULL DEFAULT 0,
  custo_unitario numeric(18,4) NOT NULL DEFAULT 0,
  lucro_fixo numeric(18,4) NOT NULL DEFAULT 0,
  lucro_unitario numeric(18,4) NOT NULL DEFAULT 0,
  ativo boolean NOT NULL DEFAULT true,
  origem varchar(30),
  origem_id integer,
  UNIQUE (origem, origem_id)
);

CREATE INDEX material_categoria ON material (categoria, ativo);

CREATE TABLE preco_m2 (
  tipo varchar(50) PRIMARY KEY,
  preco_base_m2 numeric(18,4) NOT NULL
);

CREATE TABLE item (
  id_item integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orcamento integer REFERENCES orcamento(id_orcamento) ON DELETE SET NULL ON UPDATE CASCADE,
  id_papel integer REFERENCES papel(id_papel) ON DELETE SET NULL ON UPDATE CASCADE,
  id_impressao integer REFERENCES impressao(id_impressao) ON DELETE SET NULL ON UPDATE CASCADE,
  id_material integer REFERENCES material(id_material) ON DELETE SET NULL,
  precificacao_snapshot text,
  tipo_produto varchar(100),
  quantidade integer,
  largura numeric(10,2),
  altura numeric(10,2),
  valor_unitario numeric(18,4),
  valor_total numeric(18,4)
);

CREATE TABLE acabamento_item (
  id_acabamento_item integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_acabamento integer REFERENCES acabamento(id_acabamento) ON DELETE SET NULL ON UPDATE CASCADE,
  id_item integer REFERENCES item(id_item) ON DELETE SET NULL ON UPDATE CASCADE,
  quantidade integer,
  custo_aplicado numeric(18,4)
);

CREATE TABLE item_corte (
  id_item_corte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_item integer REFERENCES item(id_item) ON DELETE SET NULL ON UPDATE CASCADE,
  id_corte integer REFERENCES corte(id_corte) ON DELETE SET NULL ON UPDATE CASCADE,
  quantidade integer,
  custo_aplicado numeric(18,4)
);

CREATE TABLE servico_item (
  id_servico_item integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_servico integer REFERENCES servico(id_servico) ON DELETE SET NULL ON UPDATE CASCADE,
  id_item integer REFERENCES item(id_item) ON DELETE SET NULL ON UPDATE CASCADE,
  quantidade integer,
  custo_aplicado numeric(18,4)
);

CREATE TABLE documento (
  id_documento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orcamento integer REFERENCES orcamento(id_orcamento) ON DELETE SET NULL ON UPDATE CASCADE,
  tipo varchar(30),
  caminho_arquivo varchar(255),
  data_geracao timestamptz
);

CREATE TABLE historico_log (
  id_log integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer REFERENCES usuario(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
  tabela_afetada varchar(50),
  id_registro integer,
  acao varchar(50),
  campo_alterado varchar(50),
  valor_antigo text,
  valor_novo text,
  data_hora timestamptz NOT NULL DEFAULT now(),
  descricao text
);

CREATE INDEX orcamento_relatorio_periodo ON orcamento (data_criacao, data_finalizacao, status);
